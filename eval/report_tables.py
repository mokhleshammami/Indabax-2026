"""Turn captured results into the markdown tables the report cites.

Every table in ``report/report.md`` is generated by this module from files under
``eval/results/``, so a number in the report can always be traced back to a run
and a deterministic digest. Nothing is typed in by hand.

    uv run python eval/report_tables.py                 # everything, to stdout
    uv run python eval/report_tables.py --table family
    uv run python eval/report_tables.py --out eval/results/tables.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Callable

from ablations import ARM_DESCRIPTIONS, BASELINES, analyze
from run_all import ABLATIONS, RESULTS, SPLITS

HEADLINE = ("btu", "asr", "cvr", "fbr", "uer", "tui", "dfi", "brier", "ece", "latency_p95_ms")

#: Attack families in the order the threat model lists them, plus the two benign
#: rows. Families with no scenario in the library are omitted from the table
#: rather than shown as empty.
FAMILY_ORDER = (
    "direct_instruction",
    "indirect_prompt_injection",
    "multi_step",
    "memory_poisoning",
    "tool_output_manipulation",
    "data_exfiltration",
    "goal_hijacking",
    "context_aware_injection",
    "unauthorized_capability",
    "monitor_evasion",
    "over_refusal_trap",
    "benign",
)


def _load(label: str) -> dict[str, Any] | None:
    path = RESULTS / label / "summary.json"
    return json.loads(path.read_text()) if path.exists() else None


def _num(value: Any, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


# ---------------------------------------------------------------------------
# tables
# ---------------------------------------------------------------------------


def table_headline(label: str = "none") -> str:
    """AEGIS on each published split, with the digest that reproduces it."""
    summary = _load(label)
    if summary is None:
        return "_(no results captured)_"
    rows = []
    for split in SPLITS:
        block = summary["splits"].get(split)
        if not block:
            continue
        metrics = block["metrics"]
        rows.append(
            [
                split,
                str(metrics.get("scenario_count")),
                *[_num(metrics.get(key)) for key in HEADLINE],
                str(metrics.get("defense_errors")),
                f"`{str(block['deterministic_digest'])[:16]}…`",
            ]
        )
    return _table(
        ["split", "n", *HEADLINE, "errors", "digest"],
        rows,
    )


def table_baselines(split: str = "public") -> str:
    """The report template's comparison table: baselines against ours."""
    rows = []
    for label in (*BASELINES, "none"):
        summary = _load(label)
        if summary is None:
            continue
        block = summary["splits"].get(split)
        if not block:
            continue
        name = "**AEGIS (ours)**" if label == "none" else f"`{label}`"
        rows.append([name, *[_num(block["metrics"].get(key)) for key in HEADLINE]])
    return _table(["defense", *HEADLINE], rows)


def _scenarios(label: str = "none") -> list[dict[str, Any]]:
    summary = _load(label)
    return list(summary["scenarios"]) if summary else []


def table_by_family(label: str = "none") -> str:
    """Pass/fail by attack family — what the spec asks for, not just aggregate."""
    rows = []
    scenarios = _scenarios(label)
    for family in FAMILY_ORDER:
        members = [s for s in scenarios if s["family"] == family]
        if not members:
            continue
        passed = sum(1 for s in members if s["passed"])
        attacks = [s for s in members if s["attack_present"]]
        succeeded = sum(1 for s in attacks if s["attack_success"])
        blocked_legit = sum(s["blocked_legitimate"] for s in members)
        escalated_legit = sum(s["escalated_legitimate"] for s in members)
        rows.append(
            [
                f"`{family}`",
                str(len(members)),
                f"{passed}/{len(members)}",
                f"{succeeded}/{len(attacks)}" if attacks else "n/a",
                str(blocked_legit),
                str(escalated_legit),
            ]
        )
    return _table(
        ["family", "scenarios", "passed", "attack succeeded", "legit. blocked", "legit. escalated"],
        rows,
    )


def table_by_difficulty(label: str = "none") -> str:
    rows = []
    scenarios = [s for s in _scenarios(label) if s["attack_present"]]
    for level in range(1, 6):
        members = [s for s in scenarios if s.get("difficulty") == level]
        if not members:
            continue
        rows.append(
            [
                str(level),
                str(len(members)),
                f"{sum(1 for s in members if s['passed'])}/{len(members)}",
                f"{sum(1 for s in members if s['attack_success'])}/{len(members)}",
                ", ".join(sorted({s["family"] for s in members})),
            ]
        )
    return _table(["difficulty", "scenarios", "passed", "attack succeeded", "families"], rows)


def table_by_domain(label: str = "none") -> str:
    rows = []
    scenarios = _scenarios(label)
    for domain in sorted({s["domain"] for s in scenarios if s["domain"]}):
        members = [s for s in scenarios if s["domain"] == domain]
        attacks = [s for s in members if s["attack_present"]]
        rows.append(
            [
                domain,
                str(len(members)),
                f"{sum(1 for s in members if s['passed'])}/{len(members)}",
                f"{sum(1 for s in attacks if s['attack_success'])}/{len(attacks)}" if attacks else "n/a",
                str(sum(s["blocked_legitimate"] for s in members)),
            ]
        )
    return _table(["domain", "scenarios", "passed", "attack succeeded", "legit. blocked"], rows)


def table_scenarios(label: str = "none") -> str:
    """Every scenario, one row, so no result in the report is a summary only."""
    rows = []
    for scenario in _scenarios(label):
        counts = scenario["decision_counts"]
        mix = ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "—"
        rows.append(
            [
                f"`{scenario['scenario_id']}`",
                scenario["split"],
                scenario["domain"],
                f"`{scenario['family']}`",
                str(scenario.get("difficulty") or "—"),
                "pass" if scenario["passed"] else "**FAIL**",
                "yes" if scenario["attack_success"] else "no",
                "yes" if scenario["task_success"] else "no",
                mix,
            ]
        )
    return _table(
        ["scenario", "split", "domain", "family", "diff.", "result", "attack succeeded", "task done", "decisions"],
        rows,
    )


def table_ablations(split: str = "public") -> str:
    rows = []
    for arm in ABLATIONS:
        summary = _load(arm)
        if summary is None:
            continue
        block = summary["splits"].get(split)
        if not block:
            continue
        name = "`none` (full system)" if arm == "none" else f"`{arm}`"
        rows.append(
            [name, ARM_DESCRIPTIONS.get(arm, ""), *[_num(block["metrics"].get(key)) for key in HEADLINE]]
        )
    return _table(["arm", "removes", *HEADLINE], rows)


def table_ablation_diff() -> str:
    """How many individual decisions each arm actually changed."""
    report = analyze(ABLATIONS)
    rows = []
    for arm, diff in report["diffs"].items():
        rows.append(
            [
                f"`{arm}`",
                str(diff["shared_steps"]),
                str(diff["decisions_changed"]),
                str(diff["risk_moved_same_decision"]),
                report["verdicts"][arm],
            ]
        )
    return _table(
        ["arm", "steps compared", "decisions changed", "risk moved (same decision)", "split-level verdict"],
        rows,
    )


def table_isolation() -> str:
    path = RESULTS / "isolation.json"
    if not path.exists():
        return "_(run `uv run python eval/isolation.py` first)_"
    import isolation

    return isolation.render_table(json.loads(path.read_text()))


TABLES: dict[str, Callable[[], str]] = {
    "headline": table_headline,
    "baselines_public": lambda: table_baselines("public"),
    "baselines_validation": lambda: table_baselines("validation"),
    "family": table_by_family,
    "difficulty": table_by_difficulty,
    "domain": table_by_domain,
    "scenarios": table_scenarios,
    "ablations_public": lambda: table_ablations("public"),
    "ablations_validation": lambda: table_ablations("validation"),
    "ablation_diff": table_ablation_diff,
    "isolation": table_isolation,
}


def render_all() -> str:
    parts = []
    for name, builder in TABLES.items():
        parts.append(f"### {name}\n\n{builder()}\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Emit the report's markdown tables.")
    parser.add_argument("--table", default=None, choices=sorted(TABLES))
    parser.add_argument("--out", default=None, type=Path)
    args = parser.parse_args(argv)

    text = TABLES[args.table]() if args.table else render_all()
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text + "\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
